// Regenerate the artifact modules from the freshly built xark output.
// Run after `xark build`, `xark setup` and `xark client` (the `setup` script).
//
//   xbc.ts + pk.ts + client-wasm.ts   the prover (circuit.xbc and sources.json, pk.bin,
//                                     client.wasm), loaded by the house's Web Worker
//   vk.ts                             the verifier (vk.bin) and its sha256, which
//                                     the page pins its verifier to
//   minesweeper.ts                    the typed client `xark client` generated
//
// Each binary module exports a `Uint8Array` decoded from a base64 literal via the
// native `Uint8Array.fromBase64` (Node ≥ 25, workerd, modern browsers; the project
// pins Node ≥ 26). base64 is the most compact source encoding (~1.33× the binary)
// and the decode is native. The bytes are inlined into the bundle, so the worker
// and the verifier need no fetch of their own.
import { createHash } from "node:crypto";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const circuit = join(here, "..", "circuits", "minesweeper");
const out = join(circuit, "target", "xark", "minesweeper");
const artifacts = join(circuit, "artifacts");

mkdirSync(artifacts, { recursive: true });

// `export const <name> = Uint8Array.fromBase64("...")`: the export is the bytes.
function emit(file, ts, name, extra = "") {
  const bytes = readFileSync(join(out, file));
  writeFileSync(
    join(artifacts, ts),
    `// Generated by scripts/gen-artifacts.mjs from ${file}: don't edit.\n` +
      `export const ${name} = Uint8Array.fromBase64("${bytes.toString("base64")}");\n` +
      extra,
  );
  console.log(`${ts}: ${name}, ${bytes.length} bytes`);
  return bytes;
}

// The key and circuit must come from one setup: a key made for another build
// proves nothing the page will accept.
const meta = JSON.parse(readFileSync(join(out, "metadata.json"), "utf8"));
const digest = readFileSync(join(out, "digest"), "utf8").trim();
if (meta.digest !== digest) {
  throw new Error(`pk.bin/vk.bin were made for circuit ${meta.digest}, but circuit.xbc is ${digest}: rerun \`xark setup\``);
}

emit(
  "circuit.xbc",
  "xbc.ts",
  "xbcBytes",
  `\n/** sources.json from the same build: a failed check names its line in the circuit. */\n` +
    `export const sources = ${JSON.stringify(readFileSync(join(out, "sources.json"), "utf8"))};\n`,
);
emit("pk.bin", "pk.ts", "pkBytes");
emit("client.wasm", "client-wasm.ts", "clientWasmBytes");
const vk = emit(
  "vk.bin",
  "vk.ts",
  "vkBytes",
  `\n/** vk.bin's sha256, as \`xark setup\` printed it: the page's verifier refuses any other key. */\n` +
    `export const keyHash = "${meta.verifying_key_sha256}";\n`,
);
if (createHash("sha256").update(vk).digest("hex") !== meta.verifying_key_sha256) {
  throw new Error("vk.bin's sha256 doesn't match metadata.json: rerun `xark setup`");
}

copyFileSync(join(out, "minesweeper.ts"), join(artifacts, "minesweeper.ts"));
console.log(`minesweeper.ts: the typed client, circuit digest ${digest}`);
